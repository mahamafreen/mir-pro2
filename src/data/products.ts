const gallery = (slug: string, order: number[] = [1, 2, 3, 4]) =>
  order.map((number) => `/assets/images/products/${slug}/${number}.jpg`);

const makeProduct = (
  input: Omit<Product, 'image' | 'images'> & {imageOrder?: number[]},
): Product => {
  const images = gallery(input.handle, input.imageOrder);
  const {imageOrder: _imageOrder, ...rest} = input;
  return {...rest, image: images[0], images};
};

